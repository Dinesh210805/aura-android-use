package com.aura.aura_ui.voice

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioFormat
import android.media.AudioTrack
import android.util.Log
import com.aura.aura_ui.agent.conversation.LiveModelResolver
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.delay
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray
import kotlinx.serialization.json.putJsonObject
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import java.io.File
import java.util.Base64
import java.util.concurrent.TimeUnit

/**
 * Plays a short sample of a Gemini Live prebuilt voice, generated by the Gemini TTS model.
 *
 * - Why TTS and not Live: the TTS models share Live's prebuilt voice set (`voiceName`), and a
 *   one-shot REST call is far cheaper than opening a Live session just to hear a voice.
 * - Contract: [play] suspends until the sample finishes; cancelling the caller stops it at once.
 * - Fails: returns false on no network, a quota error or no TTS model on the key; logged.
 * - Reads/Writes: `cacheDir/gemini_voice_preview/{voice}.pcm`, so each voice costs one API call;
 *   host `generativelanguage.googleapis.com` with the user's BYOK key.
 */
object GeminiVoicePreview {
    private const val TAG = "GeminiVoicePreview"
    private const val SAMPLE_RATE = 24_000
    private const val FALLBACK_TTS_MODEL = "models/gemini-2.5-flash-preview-tts"
    private const val PREVIEW_TEXT = "Hi, I'm AURA. Tell me what you need and I'll take care of it on your phone."

    private val json = Json { ignoreUnknownKeys = true }
    // TTS renders the whole clip before answering; OkHttp's 10 s default read timeout is too tight.
    private val client = OkHttpClient.Builder().readTimeout(30, TimeUnit.SECONDS).build()

    @Volatile private var ttsModel: String? = null

    /** Picks the TTS model from ListModels names: a `flash` one first, else any `tts` model. */
    fun pickTtsModel(names: List<String>): String? {
        val tts = names.filter { it.contains("tts") }
        return tts.firstOrNull { it.contains("flash") } ?: tts.firstOrNull()
    }

    /** Fetches (or reads the cached) sample, calls [onStart] as audio begins, returns when it ends. */
    suspend fun play(context: Context, apiKey: String, voice: String, onStart: () -> Unit = {}): Boolean {
        val pcm = load(context, apiKey, voice)?.takeIf { it.size >= 2 } ?: return false
        onStart()
        playPcm(pcm)
        return true
    }

    private suspend fun load(context: Context, apiKey: String, voice: String): ByteArray? =
        withContext(Dispatchers.IO) {
            val file = File(context.cacheDir, "gemini_voice_preview/$voice.pcm")
            if (file.exists() && file.length() > 0) return@withContext file.readBytes()
            val pcm = fetch(apiKey, voice) ?: return@withContext null
            runCatching { file.parentFile?.mkdirs(); file.writeBytes(pcm) }
            pcm
        }

    private suspend fun fetch(apiKey: String, voice: String): ByteArray? {
        val model = ttsModel
            ?: (pickTtsModel(LiveModelResolver.listModels(apiKey, "generateContent", client)) ?: FALLBACK_TTS_MODEL)
                .also { ttsModel = it }
        val body = buildJsonObject {
            putJsonArray("contents") {
                add(buildJsonObject { putJsonArray("parts") { add(buildJsonObject { put("text", PREVIEW_TEXT) }) } })
            }
            putJsonObject("generationConfig") {
                putJsonArray("responseModalities") { add(JsonPrimitive("AUDIO")) }
                putJsonObject("speechConfig") {
                    putJsonObject("voiceConfig") { putJsonObject("prebuiltVoiceConfig") { put("voiceName", voice) } }
                }
            }
        }.toString()
        val req = Request.Builder()
            .url("https://generativelanguage.googleapis.com/v1beta/$model:generateContent?key=$apiKey")
            .post(body.toRequestBody("application/json".toMediaType()))
            .build()
        return runCatching {
            client.newCall(req).execute().use { resp ->
                val text = resp.body?.string().orEmpty()
                if (!resp.isSuccessful) {
                    Log.w(TAG, "TTS ${resp.code} for $voice on $model")
                    return@use null
                }
                // PCM s16le 24 kHz mono, base64 in candidates[0].content.parts[0].inlineData.data.
                json.parseToJsonElement(text).jsonObject["candidates"]?.jsonArray?.firstOrNull()
                    ?.jsonObject?.get("content")?.jsonObject?.get("parts")?.jsonArray?.firstOrNull()
                    ?.jsonObject?.get("inlineData")?.jsonObject?.get("data")?.jsonPrimitive?.contentOrNull
                    ?.let { Base64.getDecoder().decode(it) }
            }
        }.getOrElse { Log.w(TAG, "TTS fetch failed for $voice: ${it.message}"); null }
    }

    /** Media usage, not voice-communication: outside a Live call that would route to the earpiece. */
    private suspend fun playPcm(pcm: ByteArray) {
        val track = AudioTrack.Builder()
            .setAudioAttributes(
                AudioAttributes.Builder()
                    .setUsage(AudioAttributes.USAGE_MEDIA)
                    .setContentType(AudioAttributes.CONTENT_TYPE_SPEECH)
                    .build(),
            )
            .setAudioFormat(
                AudioFormat.Builder()
                    .setEncoding(AudioFormat.ENCODING_PCM_16BIT)
                    .setSampleRate(SAMPLE_RATE)
                    .setChannelMask(AudioFormat.CHANNEL_OUT_MONO)
                    .build(),
            )
            .setBufferSizeInBytes(pcm.size)
            .setTransferMode(AudioTrack.MODE_STATIC)
            .build()
        try {
            track.write(pcm, 0, pcm.size)
            track.play()
            delay(pcm.size * 1000L / (SAMPLE_RATE * 2) + 150)
        } finally {
            runCatching { track.stop() }
            track.release()
        }
    }
}
